# POSIX port of the parts of ../scriptHelper.ps1 that bumpVersion needs, for the shellbench A/B
# (docs/dev/shellBenchPlan.md, Test 2). Sourced by .scripts/posix/*.sh; paths come from the calling
# script's own location ($0). Stock macOS tools only: jq ships with macOS 15.

# C locale: [a-z] ranges and tolower/toupper stay ASCII, as in the ps1 regexes.
export LC_ALL=C

repoRoot=$(CDPATH='' cd -- "$(dirname -- "$0")/../.." && pwd)
versionFolder=$repoRoot/src/.version
version=$versionFolder/version
versionTag=$versionFolder/versionTag
yapWords=$repoRoot/.res/yapBot.json

fail() {
    printf '%s\n' "$*" >&2
    exit 1
}

# closeOut from ../scriptHelper.ps1 with 0 seconds: a pane the sidebar script runner made for this
# script (SCRIPT_OWN_PANE) closes after a successful run. A failed wezterm call does not stop the exit.
closeOut() {
    if [ -n "${SCRIPT_OWN_PANE-}" ] && [ -n "${WEZTERM_PANE-}" ]; then
        wezterm cli kill-pane --pane-id "$WEZTERM_PANE" || true
    fi
    exit 0
}

requireVersion() {
    if [ ! -e "$version" ]; then
        mkdir -p "$versionFolder"
        printf '0.0.1\n' > "$version"
    fi
    # Trim like [string]::Trim() ($(...) already drops trailing newlines), then require exactly
    # digits.digits.digits for the whole file, like the ps1 regex.
    contents=$(cat "$version")
    contents=${contents#"${contents%%[![:space:]]*}"}
    contents=${contents%"${contents##*[![:space:]]}"}
    case $contents in
        '' | *[!0-9.]* | .* | *. | *..* | *.*.*.*) fail "Invalid $version: expected one version in X.Y.Z format" ;;
        *.*.*) ;;
        *) fail "Invalid $version: expected one version in X.Y.Z format" ;;
    esac
    printf '%s\n' "$contents"
}

# Maintenance version is X.Y.Z. Like the ps1, the version is written before the tag, so a missing
# word list leaves the bumped version without a new tag.
incrementMaintenancePatch() {
    current=$(requireVersion)
    next=$(printf '%s\n' "$current" | awk -F. '{ printf "%s.%s.%d", $1, $2, $3 + 1 }')
    printf '%s\n' "$next" > "$version"
    tag=$(newVersionTag)
    printf 'Maintenance version %s -> %s (%s)\n' "$current" "$next" "$tag"
}

# One random camelCase two-word tag from the private word list, written to versionTag.
newVersionTag() {
    [ -f "$yapWords" ] ||
        fail "Missing word list $yapWords. It is private and not in the public repo, so version tags can only be generated by the maintainer."
    # Modulo bias from 32-bit random numbers is irrelevant for a tag.
    first=$(od -An -N4 -tu4 /dev/urandom | tr -d ' ')
    second=$(od -An -N4 -tu4 /dev/urandom | tr -d ' ')
    tag=$(jq -r '.[] | select(type == "string" and test("^[A-Za-z]+$"))' "$yapWords" |
        awk -v a="$first" -v b="$second" '
            { words[NR] = $0 }
            END {
                if (!NR) exit 1
                one = words[a % NR + 1]
                two = words[b % NR + 1]
                print tolower(one) toupper(substr(two, 1, 1)) tolower(substr(two, 2))
            }') || fail "No usable words found in $yapWords."
    setVersionTag "$tag"
}

setVersionTag() {
    printf '%s\n' "$1" | grep -qx '[a-z][a-z]*[A-Z][a-z]*' ||
        fail "Invalid tag '$1': expected one camelCase two-word tag"
    printf '%s\n' "$1" > "$versionTag"
    printf '%s\n' "$1"
}
