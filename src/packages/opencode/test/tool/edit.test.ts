  describe("line endings", () => {
    const old = "alpha\nbeta\ngamma"
    const next = "alpha\nbeta-updated\ngamma"
    const alt = "alpha\nbeta\nomega"

    const normalize = (text: string, ending: "\n" | "\r\n") => {
      const normalized = text.replaceAll("\r\n", "\n")
      if (ending === "\n") return normalized
      return normalized.replaceAll("\n", "\r\n")
    }

    const count = (content: string) => {
      const crlf = content.match(/\r\n/g)?.length ?? 0
      const lf = content.match(/\n/g)?.length ?? 0
      return {
        crlf,
        lf: lf - crlf,
      }
    }

    const expectLf = (content: string) => {
      const counts = count(content)
      expect(counts.crlf).toBe(0)
      expect(counts.lf).toBeGreaterThan(0)
    }

    const expectCrlf = (content: string) => {
      const counts = count(content)
      expect(counts.lf).toBe(0)
      expect(counts.crlf).toBeGreaterThan(0)
    }

    type Input = {
      content: string
      oldString: string
      newString: string
      replaceAll?: boolean
    }

    const apply = Effect.fn("EditToolTest.lineEndings.apply")(function* (input: Input) {
      const test = yield* TestInstance
      const filePath = path.join(test.directory, "test.txt")
      yield* put(filePath, input.content)
      yield* run({
        filePath,
        oldString: input.oldString,
        newString: input.newString,
        replaceAll: input.replaceAll,
      })
      return yield* load(filePath)
    })

    it.instance("preserves LF with LF multi-line strings", () =>
      Effect.gen(function* () {
        const content = normalize(old + "\n", "\n")
        const output = yield* apply({
          content,
          oldString: normalize(old, "\n"),
          newString: normalize(next, "\n"),
        })
        expect(output).toBe(normalize(next + "\n", "\n"))
        expectLf(output)
      }),
    )

    it.instance("preserves CRLF with CRLF multi-line strings", () =>
      Effect.gen(function* () {
        const content = normalize(old + "\n", "\r\n")
        const output = yield* apply({
          content,
          oldString: normalize(old, "\r\n"),
          newString: normalize(next, "\r\n"),
        })
        expect(output).toBe(normalize(next + "\n", "\r\n"))
        expectCrlf(output)
      }),
    )

    it.instance("preserves LF when old/new use CRLF", () =>
      Effect.gen(function* () {
        const content = normalize(old + "\n", "\n")
        const output = yield* apply({
          content,
          oldString: normalize(old, "\r\n"),
          newString: normalize(next, "\r\n"),
        })
        expect(output).toBe(normalize(next + "\n", "\n"))
        expectLf(output)
      }),
    )

    it.instance("preserves CRLF when old/new use LF", () =>
      Effect.gen(function* () {
        const content = normalize(old + "\n", "\r\n")
        const output = yield* apply({
          content,
          oldString: normalize(old, "\n"),
          newString: normalize(next, "\n"),
        })
        expect(output).toBe(normalize(next + "\n", "\r\n"))
        expectCrlf(output)
      }),
    )

    it.instance("preserves LF when newString uses CRLF", () =>
      Effect.gen(function* () {
        const content = normalize(old + "\n", "\n")
        const output = yield* apply({
          content,
          oldString: normalize(old, "\n"),
          newString: normalize(next, "\r\n"),
        })
        expect(output).toBe(normalize(next + "\n", "\n"))
        expectLf(output)
      }),
    )

    it.instance("preserves CRLF when newString uses LF", () =>
      Effect.gen(function* () {
        const content = normalize(old + "\n", "\r\n")
        const output = yield* apply({
          content,
          oldString: normalize(old, "\r\n"),
          newString: normalize(next, "\n"),
        })
        expect(output).toBe(normalize(next + "\n", "\r\n"))
        expectCrlf(output)
      }),
    )

    it.instance("preserves LF with mixed old/new line endings", () =>
      Effect.gen(function* () {
        const content = normalize(old + "\n", "\n")
        const output = yield* apply({
          content,
          oldString: "alpha\nbeta\r\ngamma",
          newString: "alpha\r\nbeta\nomega",
        })
        expect(output).toBe(normalize(alt + "\n", "\n"))
        expectLf(output)
      }),
    )

    it.instance("preserves CRLF with mixed old/new line endings", () =>
      Effect.gen(function* () {
        const content = normalize(old + "\n", "\r\n")
        const output = yield* apply({
          content,
          oldString: "alpha\r\nbeta\ngamma",
          newString: "alpha\nbeta\r\nomega",
        })
        expect(output).toBe(normalize(alt + "\n", "\r\n"))
        expectCrlf(output)
      }),
    )

    it.instance("replaceAll preserves LF for multi-line blocks", () =>
      Effect.gen(function* () {
        const blockOld = "alpha\nbeta"
        const blockNew = "alpha\nbeta-updated"
        const content = normalize(blockOld + "\n" + blockOld + "\n", "\n")
        const output = yield* apply({
          content,
          oldString: normalize(blockOld, "\n"),
          newString: normalize(blockNew, "\n"),
          replaceAll: true,
        })
        expect(output).toBe(normalize(blockNew + "\n" + blockNew + "\n", "\n"))
        expectLf(output)
      }),
    )

    it.instance("replaceAll preserves CRLF for multi-line blocks", () =>
      Effect.gen(function* () {
        const blockOld = "alpha\nbeta"
        const blockNew = "alpha\nbeta-updated"
        const content = normalize(blockOld + "\n" + blockOld + "\n", "\r\n")
        const output = yield* apply({
          content,
          oldString: normalize(blockOld, "\r\n"),
          newString: normalize(blockNew, "\r\n"),
          replaceAll: true,
        })
        expect(output).toBe(normalize(blockNew + "\n" + blockNew + "\n", "\r\n"))
        expectCrlf(output)
      }),
    )

    it.instance("matches across mixed line endings and keeps each region's endings", () =>
      Effect.gen(function* () {
        const test = yield* TestInstance
        const mostlyLf = path.join(test.directory, "mostly-lf.txt")
        const mostlyCrlf = path.join(test.directory, "mostly-crlf.txt")
        yield* put(mostlyLf, "head\r\nAAA OLD BBB\ntail\n")
        yield* put(mostlyCrlf, "one\r\ntwo\r\nthree\nfour\r\n")

        yield* run({ filePath: mostlyLf, oldString: "AAA OLD BBB", newString: "AAA NEW\nLINE2" })
        yield* run({ filePath: mostlyLf, oldString: "LINE2\ntail", newString: "LINE2\nTAIL" })
        yield* run({ filePath: mostlyCrlf, oldString: "o\nthree\nfo", newString: "O\nTHREE\nFO" })
        yield* run({ filePath: mostlyCrlf, oldString: "one", newString: "ONE\nUNO" })

        expect(yield* load(mostlyLf)).toBe("head\r\nAAA NEW\nLINE2\nTAIL\n")
        expect(yield* load(mostlyCrlf)).toBe("ONE\r\nUNO\r\ntwO\r\nTHREE\nFOur\r\n")
      }),
    )

    it.instance("keeps the endings of unchanged and in-place lines inside a multi-line match", () =>
      Effect.gen(function* () {
        const test = yield* TestInstance
        // A CRLF file with a block pasted in from an LF editor, edited with surrounding context.
        const filePath = path.join(test.directory, "store.cs")
        yield* put(filePath, "All(item.Sku);\r\n\r\nFind(sku);\r\n\r\nvoid Add()\n{\n  _items[item.Sku] = item;\n}\r\n")

        yield* run({
          filePath,
          oldString: "All(item.Sku);\n\nFind(sku);\n\nvoid Add()\n{\n  _items[item.Sku] = item;\n}",
          newString:
            "All(item.Code);\n\nFind(code);\n\nvoid Add()\n{\n  _items[item.Code] = item;\n}\n\nbool Remove(string code)\n{\n}",
        })

        expect(yield* load(filePath)).toBe(
          "All(item.Code);\r\n\r\nFind(code);\r\n\r\nvoid Add()\n{\n  _items[item.Code] = item;\n}\r\n\r\nbool Remove(string code)\r\n{\r\n}\r\n",
        )
      }),
    )

    it.instance("applies edits that differ only in \\r to the exact bytes", () =>
      Effect.gen(function* () {
        const test = yield* TestInstance
        const strip = path.join(test.directory, "strip.sh")
        const whole = path.join(test.directory, "whole.sh")
        const add = path.join(test.directory, "add.bat")
        yield* put(strip, "a\r\nb\r\n")
        yield* put(whole, "x\r\ny\r\n")
        yield* put(add, "p\nq\n")

        yield* run({ filePath: strip, oldString: "\r", newString: "", replaceAll: true })
        yield* run({ filePath: whole, oldString: "x\r\ny\r\n", newString: "x\ny\n" })
        yield* run({ filePath: add, oldString: "p\nq", newString: "p\r\nq" })
        expect((yield* fail({ filePath: add, oldString: "p\nq", newString: "p\r\nq" })).message).toContain(
          "already has those line endings",
        )

        expect(yield* load(strip)).toBe("a\nb\n")
        expect(yield* load(whole)).toBe("x\ny\n")
        expect(yield* load(add)).toBe("p\r\nq\n")
      }),
    )

    it.instance("fails instead of reporting success when the edit leaves the file unchanged", () =>
      Effect.gen(function* () {
        const test = yield* TestInstance
        const filePath = path.join(test.directory, "same.txt")
        yield* put(filePath, "value = 1\n")

        // The line-trimmed matcher finds the line, and the replacement writes the same bytes back.
        expect((yield* fail({ filePath, oldString: " value = 1", newString: "value = 1" })).message).toContain(
          "No changes to apply: the edit leaves",
        )
        expect(yield* load(filePath)).toBe("value = 1\n")
      }),
    )
  })

  describe("concurrent editing", () => {
    it.instance("preserves concurrent edits to different sections of the same file", () =>
      Effect.gen(function* () {
        const test = yield* TestInstance
        const filepath = path.join(test.directory, "file.txt")
        yield* put(filepath, "top = 0\nmiddle = keep\nbottom = 0\n")

        const firstAsk = yield* Deferred.make<void>()
        let asks = 0
        const delayedCtx = {
          ...ctx,
          ask: () =>
            Effect.gen(function* () {
              asks++
              if (asks !== 1) return
              yield* Deferred.succeed(firstAsk, undefined)
              yield* Effect.sleep("50 millis")
            }),
        }

        const first = yield* run(
          {
            filePath: filepath,
            oldString: "top = 0",
            newString: "top = 1",
          },
          delayedCtx,
        ).pipe(Effect.forkScoped)

        yield* Deferred.await(firstAsk)
        yield* Effect.all([
          Fiber.join(first),
          run(
            {
              filePath: filepath,
              oldString: "bottom = 0",
              newString: "bottom = 2",
            },
            delayedCtx,
          ),
        ])

        expect(yield* load(filepath)).toBe("top = 1\nmiddle = keep\nbottom = 2\n")
      }),
    )
  })
